// Facilitator session lifecycle with Chromium's fake camera. The fake stream has
// no hands, so this checks recording, storage and export only, never accuracy.
const { chromium, launchOptions, BASE, OUT } = require('./browser.cjs')
const path = require('node:path')
const fs = require('node:fs')
const { spawnSync } = require('node:child_process')
const checks = []
const check = (name, ok, detail) => { checks.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${detail ? ' ' + JSON.stringify(detail) : ''}`) }

;(async () => {
  fs.mkdirSync(OUT, { recursive: true })
  const browser = await chromium.launch(launchOptions({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] }))
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, permissions: ['camera'], acceptDownloads: true })
  const page = await context.newPage(), errors = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => requests.push({ method: request.method(), url: request.url() }))
  await page.goto(`${BASE}/sign/validate`, { waitUntil: 'networkidle' })
  const notice = () => page.locator('.train-notice').textContent()
  await page.getByRole('button', { name: 'Create session' }).click()
  check('a session needs a pseudonymous signer code', (await notice()).includes('pseudonymous signer code'))
  await page.getByLabel('Pseudonymous signer code').fill('s-901')
  await page.getByLabel('Consent record ID').fill('consent-test-1')
  for (const name of ['Word sequences', 'Letters A–Z', 'Digits 0–9']) await page.getByLabel(name).uncheck()
  await page.getByLabel('Repeats per sign').fill('1')
  await page.getByLabel('Non-sign activity per block (seconds)').fill('0')
  await page.getByRole('button', { name: 'Create session' }).click()
  check('a session needs recorded consent', (await notice()).includes('Confirm that written informed consent'))
  await page.screenshot({ path: path.join(OUT, 'validation-setup.png'), fullPage: true })
  await page.getByLabel(/Written informed consent is recorded/).check()
  await page.getByRole('button', { name: 'Create session' }).click()
  check('session plan is created from the priority words', (await notice()).includes('Session ready with 15 trials'))

  await page.locator('.sign-camera-button').click()
  // The first visit shows the camera privacy primer, which needs its own confirmation.
  await page.getByRole('button', { name: /Got it\. Open the camera/ }).click({ timeout: 5000 }).catch(() => {})
  await page.getByText('Recognition ready.').waitFor({ timeout: 90000 })
  await page.getByRole('button', { name: 'Start trial' }).click()
  check('a running trial hides recognition output from the signer', await page.locator('.validation-trial small').textContent().then(text => text.startsWith('Recording')) && await page.locator('.validation-review').count() === 0)
  await page.waitForTimeout(1500)
  await page.getByRole('button', { name: 'End trial' }).click()
  check('review shows what was recognized', (await page.locator('.validation-review').textContent()).includes('nothing committed'))
  await page.screenshot({ path: path.join(OUT, 'validation-review.png') })
  await page.getByRole('button', { name: 'Counted' }).click()
  check('session advances to the next trial', (await page.locator('.validation-run .eyebrow').first().textContent()).includes('Trial 2 of 15'))
  const stored = await page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('yap-render-validation-v1:')).map(key => JSON.parse(localStorage.getItem(key))))
  check('trial is stored on this device', stored.length === 1 && stored[0].trials.length === 1 && stored[0].trials[0].outcome === 'ok')
  check('session report refuses an independent claim', (await page.locator('.validation-independence').first().textContent()).includes('Not an independent signer evaluation: 0 unseen ISL signers'))

  await page.getByRole('button', { name: 'Start trial' }).click()
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { value: true, configurable: true }); document.dispatchEvent(new Event('visibilitychange')) })
  await page.waitForTimeout(500)
  check('camera loss discards an unfinished trial', (await notice()).includes('unfinished trial was discarded') && await page.evaluate(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find(key => key.startsWith('yap-render-validation-v1:')))).trials.length) === 1)
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { value: false, configurable: true }) })

  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export JSON' }).click()])
  const file = path.join(OUT, 'validation-export.json')
  await download.saveAs(file)
  const exported = fs.readFileSync(file, 'utf8')
  check('export holds outputs and timings, no frames or landmarks', JSON.parse(exported).schema === 'isl-signer-validation-v1' && !/landmark|frame|image/i.test(exported))
  const script = spawnSync(process.execPath, [path.join(__dirname, '../../scripts/evaluate-signer-validation.cjs'), file], { encoding: 'utf8' })
  check('report script accepts the export', script.status === 0 && script.stdout.includes('Not an independent signer evaluation'), script.stderr)
  const origin = new URL(BASE).origin
  check('nothing is uploaded', requests.every(request => request.method === 'GET' && (request.url.startsWith(origin) || /^(data|blob):/.test(request.url))))

  await page.getByRole('button', { name: 'Leave session' }).click()
  await page.getByRole('button', { name: 'Resume' }).click()
  check('a stored session can be resumed', (await page.locator('.validation-run .eyebrow').first().textContent()).includes('Trial 2 of 15'))
  await page.screenshot({ path: path.join(OUT, 'validation-run.png') })
  await page.getByRole('button', { name: 'Leave session' }).click()
  await page.getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('button', { name: 'Confirm delete' }).click()
  check('delete needs confirmation and removes the stored session', await page.evaluate(() => !Object.keys(localStorage).some(key => key.startsWith('yap-render-validation-v1:'))))
  check('no browser exceptions', errors.length === 0, errors)
  await browser.close()
  console.log(`${checks.filter(Boolean).length}/${checks.length} validation checks passed`)
  process.exit(checks.every(Boolean) ? 0 : 1)
})().catch(error => { console.error(error); process.exit(2) })
