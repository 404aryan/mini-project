// Isolated fake-camera UI tests; these do not measure ISL or webcam accuracy.
const { chromium, launchOptions, BASE, OUT } = require('./browser.cjs')
const path = require('node:path')
const fs = require('node:fs')
const checks = []
const check = (name, ok, detail) => { checks.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${detail ? ' ' + JSON.stringify(detail) : ''}`) }

;(async () => {
  fs.mkdirSync(OUT, { recursive: true })
  const browser = await chromium.launch(launchOptions({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] }))
  const context = await browser.newContext({ viewport: { width: 1366, height: 768 }, permissions: ['camera'] })
  const page = await context.newPage(), errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${BASE}/?mode=sign&recognizer=words`, { waitUntil: 'networkidle' })
  await page.locator('.sign-viewfinder').waitFor({ state: 'visible' })
  await page.waitForTimeout(900)
  for (const [width, height] of [[1366,768],[1920,1080],[1280,720],[390,844],[375,812]]) {
    await page.setViewportSize({ width, height })
    await page.waitForTimeout(250)
    const geometry = await page.evaluate(() => {
      const frame = document.querySelector('.sign-viewfinder').getBoundingClientRect()
      const transcript = document.querySelector('.sign-transcript').getBoundingClientRect()
      const actions = document.querySelector('.sign-text-actions').getBoundingClientRect()
      const stage = document.querySelector('.sign-stage')
      return { gap: transcript.top - frame.bottom, cameraHeight: frame.height, actionsBottom: actions.bottom,
        available: innerHeight - 88, overflow: stage.scrollWidth > stage.clientWidth,
        fit: getComputedStyle(document.querySelector('.sign-camera-video')).objectFit }
    })
    check(`camera and caption controls fit ${width}x${height}`, geometry.gap <= 2 && geometry.gap >= -1 && geometry.actionsBottom <= geometry.available && geometry.cameraHeight >= 210 && !geometry.overflow && geometry.fit === 'contain', geometry)
    await page.screenshot({ path: path.join(OUT, `camera-${width}x${height}.png`) })
  }
  await page.setViewportSize({ width: 1366, height: 768 })
  // Text zoom/short viewport: content may scroll but may not clip horizontally.
  await page.evaluate(() => document.documentElement.style.fontSize = '200%')
  check('200% text zoom allows accessible scrolling without horizontal overflow', await page.evaluate(() => {
    const stage = document.querySelector('.sign-stage')
    const camera = document.querySelector('.sign-viewfinder').getBoundingClientRect()
    const start = document.querySelector('.sign-camera-button').getBoundingClientRect()
    return stage.scrollWidth <= stage.clientWidth && getComputedStyle(stage).overflowY === 'auto' && start.top >= camera.top && start.bottom <= camera.bottom
  }))
  await page.screenshot({ path: path.join(OUT, 'camera-text-zoom.png') })
  await page.evaluate(() => document.documentElement.style.fontSize = '')
  await page.getByRole('button', { name: 'Edit text', exact: true }).click()
  await page.getByRole('textbox', { name: 'Edit raw transcript' }).fill('HELLO THANK YOU')
  await page.getByRole('button', { name: 'Edit text', exact: true }).click()
  const preview = page.locator('.sign-camera-video')
  await page.getByRole('button', { name: 'Mirror preview', exact: true }).click()
  check('mirror changes preview only', await preview.getAttribute('data-mirrored') === 'false' && await preview.evaluate(video => getComputedStyle(video).transform) === 'none')
  await page.locator('.sign-camera-button').click()
  await page.waitForFunction(() => document.querySelector('.sign-stage.is-live') && document.querySelector('.sign-camera-video').srcObject, null, { timeout: 30000 })
  await page.evaluate(() => window.__originalCameraStream = document.querySelector('.sign-camera-video').srcObject)
  const fullscreen = page.getByRole('button', { name: 'Fullscreen camera and transcript' })
  await fullscreen.click()
  await page.locator('.sign-stage.is-expanded').waitFor()
  check('fullscreen contains video, transcript and controls', await page.evaluate(() => {
    const stage = document.querySelector('.sign-stage.is-expanded')
    return !!stage?.querySelector('.sign-camera-video') && !!stage.querySelector('.sign-transcript') && !!stage.querySelector('.sign-camera-controls') && getComputedStyle(document.querySelector('.mode-dock')).visibility === 'hidden'
  }))
  await page.screenshot({ path: path.join(OUT, 'camera-fullscreen.png') })
  await page.getByRole('button', { name: 'Exit expanded view' }).click()
  await page.waitForFunction(() => !document.querySelector('.sign-stage.is-expanded'))
  check('exit preserves camera stream and caption', await page.evaluate(() => document.querySelector('.sign-camera-video').srcObject === window.__originalCameraStream && document.querySelector('.sign-raw-line').textContent === 'HELLO\u00a0THANK\u00a0YOU'))
  check('exit restores fullscreen button focus', await fullscreen.evaluate(button => button === document.activeElement))
  await fullscreen.click()
  await page.locator('.sign-stage.is-expanded').waitFor()
  await page.keyboard.press('Escape')
  await page.waitForTimeout(450)
  check('Escape leaves fullscreen while keeping sign workspace', await page.locator('.sign-stage.is-expanded').count() === 0 && new URL(page.url()).searchParams.get('mode') === 'sign')
  await page.getByRole('button', { name: 'Pause camera', exact: true }).click()
  check('pause stops tracks and preserves transcript', await page.evaluate(() => !document.querySelector('.sign-camera-video').srcObject && window.__originalCameraStream.getTracks().every(track => track.readyState === 'ended') && document.querySelector('.sign-raw-line').textContent.includes('HELLO')))
  await page.getByRole('button', { name: 'Edit text', exact: true }).click()
  await page.getByRole('textbox', { name: 'Edit raw transcript' }).fill('HELLO '.repeat(180))
  check('long captions scroll to the latest text', await page.locator('.sign-raw-line').evaluate(line => line.scrollHeight > line.clientHeight && line.scrollHeight - line.scrollTop - line.clientHeight < 2))
  await page.locator('.sign-raw-line').evaluate(line => { line.scrollTop = 0; line.dispatchEvent(new Event('scroll')) })
  await page.getByRole('textbox', { name: 'Edit raw transcript' }).fill('HELLO '.repeat(180) + 'THANK YOU')
  check('reading earlier captions does not jump to the bottom', await page.locator('.sign-raw-line').evaluate(line => line.scrollTop === 0))
  await page.getByRole('button', { name: 'Edit text', exact: true }).click()
  await page.locator('.sign-workspace-settings > summary').click()
  await page.locator('.sign-vocabulary-coverage > summary').click()
  await page.getByRole('searchbox').fill('hi')
  await page.waitForFunction(() => document.querySelector('.sign-coverage-list')?.textContent.includes('Bundled'))
  check('searching hi finds canonical HELLO with coverage', (await page.locator('.sign-coverage-list').textContent()).includes('HELLO'))
  await page.getByRole('searchbox').fill('letter:I')
  check('letter I has its own vocabulary entry', await page.locator('.sign-coverage-list > div').count() === 1 && (await page.locator('.sign-coverage-list').textContent()).includes('letter'))
  check('no browser exceptions', errors.length === 0, errors)
  await context.close()

  const fallback = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await fallback.addInitScript(() => {
    HTMLElement.prototype.requestFullscreen = () => Promise.reject(new Error('Simulated browser refusal'))
  })
  const second = await fallback.newPage()
  await second.goto(`${BASE}/?mode=sign`, { waitUntil: 'networkidle' })
  await second.getByRole('button', { name: 'Fullscreen camera and transcript' }).click()
  await second.locator('.sign-stage.is-expanded').waitFor()
  check('refused fullscreen falls back to expanded view', (await second.locator('.sign-transcript-feedback').textContent()).includes('Expanded view'))
  await second.screenshot({ path: path.join(OUT, 'camera-expanded-mobile.png') })
  await second.keyboard.press('Escape')
  await second.waitForTimeout(450)
  check('fallback Escape returns without closing camera workspace', await second.locator('.sign-stage.is-expanded').count() === 0 && new URL(second.url()).searchParams.get('mode') === 'sign')
  await second.keyboard.press('Escape')
  check('second Escape closes signing workspace', !new URL(second.url()).searchParams.has('mode'))
  await browser.close()
  console.log(`${checks.filter(Boolean).length}/${checks.length} camera checks passed`)
  process.exit(checks.every(Boolean) ? 0 : 1)
})().catch(error => { console.error(error); process.exit(2) })
